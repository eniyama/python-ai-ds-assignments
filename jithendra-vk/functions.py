def is_prime(n):
    if n <= 1:
        return False
    for i in range(2, int(n**0.5) + 1):
        if n % i == 0:
            return False
    return True

# Print all prime numbers between 1 and 50
primes = [n for n in range(1, 51) if is_prime(n)]
print(primes)

def calculate_bill(item, price, quantity=1, discount=0):
    total = price * quantity
    total_after_discount = total * (1 - discount / 100)
    return total_after_discount


# 1. Using only positional arguments
bill1 = calculate_bill("Book", 20, 3, 10)
print(f"Positional arguments: ${bill1:.2f}")

# 2. Using keyword arguments in a different order
bill2 = calculate_bill(discount=15, item="Headphones", quantity=2, price=50)
print(f"Keyword arguments (reordered): ${bill2:.2f}")

# 3. Relying on default values for quantity (1) and discount (0)
bill3 = calculate_bill("Laptop", 1000)
print(f"Default values used: ${bill3:.2f}")

