def fibonacci(n):
    # Base case: return 0 for n=0, and 1 for n=1
    if n <= 0:
        return 0
    elif n == 1:
        return 1

    # Recursive case: sum of the two preceding numbers
    return fibonacci(n - 1) + fibonacci(n - 2)


# Print the first 10 Fibonacci numbers (n = 0 to 9)
for i in range(10):
    print(fibonacci(i), end=" " if i < 9 else "\n")

def make_multiplier(factor):
    def multiply(x):
        return x * factor

    return multiply


# Create double and triple functions
double = make_multiplier(2)
triple = make_multiplier(3)

